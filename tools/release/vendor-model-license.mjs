#!/usr/bin/env node
// Release tool (S10, PRD-006, PRD-007): vendor the model licence text so every
// required notice is readable offline. The text is copied mechanically from the
// licensor's own pages — it is never retyped or edited by hand.
//
//   node tools/release/vendor-model-license.mjs
//
// Sources:
//   - Cohere Labs "CC-BY-NC 4.0 License with Acceptable Use Addendum"
//     (the licence linked from the Tiny Aya Global model card)
//   - Creative Commons BY-NC 4.0 legal code, official plain text
// Output: src/features/about/notices/modelLicenseText.ts (notice ID
// tiny-aya-cc-by-nc-4.0-v1) plus a provenance record with SHA-256 digests.
// Legal review of the vendored text is a release prerequisite.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = path.join(root, 'src/features/about/notices');
const COHERE_URL = 'https://cohere.com/cohere-labs-cc-by-nc-license';
const CC_URL = 'https://creativecommons.org/licenses/by-nc/4.0/legalcode.txt';
const ACCEPTABLE_USE_URL = 'https://docs.cohere.com/docs/cohere-labs-acceptable-use-policy';

async function get(url) {
  const response = await fetch(url, {redirect: 'follow'});
  if (!response.ok) {
    throw new Error(`${url}: HTTP ${response.status}`);
  }
  return response.text();
}

function decodeEntities(text) {
  const named = {amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rsquo: '’', lsquo: '‘', ldquo: '“', rdquo: '”', mdash: '—', ndash: '–'};
  return text
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => named[n] ?? m);
}

function htmlToText(html) {
  const body = html
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .replace(/<style[\s\S]*?<\/style>/gi, '')
    .replace(/<(\/p|\/h[1-6]|\/li|br\s*\/?|\/div|\/ol|\/ul)>/gi, '\n')
    .replace(/<[^>]+>/g, '');
  const text = decodeEntities(body);
  const start = text.indexOf('Creative Commons Attribution-NonCommercial 4.0 International Public');
  if (start === -1) {
    throw new Error('licence heading not found on the Cohere page; the page layout changed');
  }
  // The licence ends before the site footer; the addendum is its last section.
  const tail = text.slice(start);
  const footer = tail.search(/\n\s*(Products|Company|Cohere ©|Subscribe|Get started)\s*\n/);
  let licence = footer === -1 ? tail : tail.slice(0, footer);
  // The licence's final sentence; anything after it is page chrome (tags, footer).
  const END = 'incorporated by reference into this Public License.';
  const end = licence.lastIndexOf(END);
  if (end !== -1) {
    licence = licence.slice(0, end + END.length);
  }
  return licence
    .split('\n')
    .map(line => line.replace(/\s+/g, ' ').trim())
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

const cohereHtml = await get(COHERE_URL);
const cohereText = htmlToText(cohereHtml);
if (!/Acceptable Use Addendum/i.test(cohereText) || cohereText.length < 8000) {
  throw new Error('extracted Cohere licence text looks incomplete; refusing to write it');
}
const ccText = (await get(CC_URL)).replace(/\r\n/g, '\n').trim();
if (!/Attribution-NonCommercial 4.0 International/.test(ccText)) {
  throw new Error('unexpected Creative Commons legal code content');
}

const sha = text => crypto.createHash('sha256').update(text).digest('hex');
const provenance = {
  notice_id: 'tiny-aya-cc-by-nc-4.0-v1',
  retrieved_at: new Date().toISOString(),
  sources: [
    {title: 'CC-BY-NC 4.0 License with Acceptable Use Addendum (Cohere Labs)', url: COHERE_URL, sha256: sha(cohereText)},
    {title: 'Creative Commons Attribution-NonCommercial 4.0 International — legal code', url: CC_URL, sha256: sha(ccText)},
  ],
  acceptable_use_policy_url: ACCEPTABLE_USE_URL,
  review: {status: 'pending-legal-review', reviewer: null},
};

fs.mkdirSync(outDir, {recursive: true});
fs.writeFileSync(path.join(outDir, 'model-license.provenance.json'), JSON.stringify(provenance, null, 2) + '\n');
fs.writeFileSync(
  path.join(outDir, 'modelLicenseText.ts'),
  `// GENERATED by tools/release/vendor-model-license.mjs — do not edit by hand.
// Verbatim licence text vendored from the licensor for offline display (S10).
export const MODEL_LICENSE_NOTICE_ID = 'tiny-aya-cc-by-nc-4.0-v1';
export const MODEL_LICENSE_SOURCE_URL = ${JSON.stringify(COHERE_URL)};
export const MODEL_ACCEPTABLE_USE_URL = ${JSON.stringify(ACCEPTABLE_USE_URL)};
export const MODEL_LICENSE_TEXT = ${JSON.stringify(cohereText)};
export const CC_BY_NC_4_LEGAL_CODE = ${JSON.stringify(ccText)};
`,
);
console.log(JSON.stringify({cohereChars: cohereText.length, ccChars: ccText.length, provenance: provenance.sources.map(s => s.sha256.slice(0, 12))}));
