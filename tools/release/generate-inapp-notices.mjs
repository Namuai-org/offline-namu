#!/usr/bin/env node
// Release tool (S10): build the in-app, offline-readable open-source notices.
//
//   node tools/release/generate-inapp-notices.mjs
//
// Output: src/features/about/notices/bundledNotices.ts containing
//   - the full licence texts of the direct runtime dependencies and the
//     bundled native inference engine (llama.cpp via llama.rn),
//   - a name/version/licence line for every package in the production closure,
//   - the DM Sans (OFL 1.1) and Material Symbols (Apache-2.0) licence texts.
// The exhaustive per-package texts live in docs/notices/THIRD_PARTY_NOTICES.md.
import fs from 'node:fs';
import path from 'node:path';
import {productionClosure, readLock, repoRoot, nameFromLocation} from './lock-closure.mjs';

const pkg = JSON.parse(fs.readFileSync(path.join(repoRoot, 'package.json'), 'utf8'));
const {lock} = readLock();

function licenceFile(dir) {
  if (!fs.existsSync(dir)) {
    return null;
  }
  const name = fs.readdirSync(dir).find(f => /^(licen[sc]e|copying)(\.|$)/i.test(f));
  return name ? fs.readFileSync(path.join(dir, name), 'utf8').replace(/\r\n/g, '\n').trim() : null;
}

const sections = [];
for (const name of Object.keys(pkg.dependencies).sort()) {
  const dir = path.join(repoRoot, 'node_modules', name);
  const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const text = licenceFile(dir);
  sections.push(`${name} ${meta.version} — ${meta.license ?? 'see text'}\n\n${text ?? '(licence text: see package)'}`);
}
const llamaCpp = licenceFile(path.join(repoRoot, 'node_modules/llama.rn/cpp'));
if (llamaCpp) {
  sections.push(`llama.cpp / ggml (bundled inside llama.rn, build b10256) — MIT\n\n${llamaCpp}`);
}

const closure = productionClosure(lock).locations;
const lines = [...new Set(
  closure.map(location => {
    const entry = lock.packages[location];
    return `${nameFromLocation(location)} ${entry.version} — ${entry.license ?? 'see docs/notices'}`;
  }),
)].sort((a, b) => a.localeCompare(b));

const openSource = [
  'Namu includes the following open-source software.',
  '',
  sections.join('\n\n----------------------------------------\n\n'),
  '',
  '========================================',
  `All npm packages in the production dependency closure (${lines.length}):`,
  '',
  lines.join('\n'),
].join('\n');

const fonts = [
  'DM Sans — Copyright 2014 The DM Sans Project Authors. SIL Open Font License 1.1.',
  'Namu bundles static Regular, Medium and SemiBold instances generated from the official variable font.',
  '',
  fs.readFileSync(path.join(repoRoot, 'src/design/licenses/DMSans-OFL.txt'), 'utf8').trim(),
  '',
  '----------------------------------------',
  '',
  'Material Symbols Rounded — Copyright Google LLC. Apache License 2.0.',
  'Namu bundles a subset of the icon font. Namu is not affiliated with Google.',
  '',
  fs.readFileSync(path.join(repoRoot, 'src/design/licenses/MaterialSymbols-Apache-2.0.txt'), 'utf8').trim(),
].join('\n');

const out = path.join(repoRoot, 'src/features/about/notices/bundledNotices.ts');
fs.writeFileSync(
  out,
  `// GENERATED by tools/release/generate-inapp-notices.mjs — do not edit by hand.
export const OPEN_SOURCE_NOTICES = ${JSON.stringify(openSource)};
export const FONT_NOTICES = ${JSON.stringify(fonts)};
`,
);
console.log(JSON.stringify({directSections: sections.length, closurePackages: lines.length, bytes: fs.statSync(out).size}));
